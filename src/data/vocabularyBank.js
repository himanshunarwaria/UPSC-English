// ── Export functions ────────────────────────────────────────────────────────

export function getVocabularyBank() {
  return VOCABULARY_BANK;
}

export function getVocabularyById(id) {
  return VOCABULARY_BANK.find(v => v.id === id);
}

export function getVocabularyByLevel(level) {
  return VOCABULARY_BANK.filter(v => v.level === level);
}

export function getVocabularyByTopic(topic) {
  return VOCABULARY_BANK.filter(v => v.topic === topic);
}

export function getVocabularyTopics() {
  return [...new Set(VOCABULARY_BANK.map(v => v.topic))].sort();
}

export function searchVocabulary(query) {
  const q = query.toLowerCase();
  return VOCABULARY_BANK.filter(v =>
    v.common_word.toLowerCase().includes(q) ||
    v.advanced_word.toLowerCase().includes(q) ||
    v.meaning.toLowerCase().includes(q) ||
    v.topic.toLowerCase().includes(q)
  );
}
